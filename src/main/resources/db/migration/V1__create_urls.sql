CREATE TABLE urls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code VARCHAR(7) COLLATE "C" NOT NULL,
    original_url VARCHAR(2048) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    disabled BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_urls_short_code UNIQUE (short_code),
    CONSTRAINT ck_urls_short_code CHECK (short_code ~ '^[A-Za-z0-9]{7}$'),
    CONSTRAINT ck_urls_expiration CHECK (expires_at IS NULL OR expires_at > created_at)
);
